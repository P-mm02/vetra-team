export function portfolioText(message: string, locale: CmsLocale): string {
  if (locale === 'en' || !message) return message
  if (thai[message]) return thai[message]
  let match: RegExpMatchArray | null
  if ((match = message.match(/^Preparing (\d+) images? in your browser…$/))) return `กำลังเตรียมรูปภาพ ${match[1]} รูปในเบราว์เซอร์…`
  if ((match = message.match(/^(\d+) images? ready\. Files will upload when you save\.$/))) return `เตรียมรูปภาพ ${match[1]} รูปแล้ว ไฟล์จะอัปโหลดเมื่อคุณบันทึก`
  if (message === 'Uploading cover image…') return 'กำลังอัปโหลดภาพปก…'
  if ((match = message.match(/^Uploading gallery image (\d+) of (\d+)…$/))) return `กำลังอัปโหลดรูปภาพในแกลเลอรี ${match[1]} จาก ${match[2]} รูป…`
  if ((match = message.match(/^(\d+) unused images? could not be deleted\. Retry cleanup before another save\.$/))) return `ลบรูปภาพที่ไม่ได้ใช้ ${match[1]} รูปไม่สำเร็จ กรุณาลองล้างรูปภาพอีกครั้งก่อนบันทึก`
  if ((match = message.match(/^Request failed \((\d+)\)$/))) return `คำขอไม่สำเร็จ (รหัส ${match[1]}) กรุณาลองอีกครั้ง`
  if ((match = message.match(/^Restored (.+)\.$/))) return `กู้คืน ${match[1]} แล้ว`
  if ((match = message.match(/^Cleanup finished: (\d+) unused uploads? removed(?:, (\d+) could not be removed)?\.$/))) return `ล้างรูปภาพเสร็จแล้ว: ลบรูปภาพที่ไม่ได้ใช้ ${match[1]} รูป${match[2] ? ` และลบไม่สำเร็จ ${match[2]} รูป` : ''}`
  if (message.startsWith('Could not restore this account (')) return 'กู้คืนบัญชีนี้ไม่สำเร็จ บัญชีอาจเปลี่ยนแปลงหรือไม่สามารถใช้ชื่อและอีเมลเดิมได้ กรุณารีเฟรชถังขยะ'
  // Retry notices combine a service error and a recovery instruction.
  for (const [english, translated] of Object.entries(thai)) {
    if (message.endsWith(' ' + english)) return `${portfolioText(message.slice(0, -english.length - 1), locale)} ${translated}`
  }
  return 'ไม่สามารถดำเนินการได้ กรุณาตรวจสอบข้อมูลและลองอีกครั้ง หากยังพบปัญหาให้ติดต่อผู้ดูแลระบบ'
}

